// Builds the Studio tab extension (app/extension) as a .zip for this Link Checker site: the
// manifest gets this page's address, so the extension's content script runs here and nowhere
// else. Made in the browser, so every deployment offers a copy for its own address.
import background from '../../../extension/background.js?raw';
import content from '../../../extension/content.js?raw';
import readme from '../../../extension/README.md?raw';
import template from '../../../extension/manifest.template.json?raw';

/** This site's address as a match pattern. Chrome match patterns can't hold a port. */
const sitePattern = () => `${location.protocol}//${location.hostname}`;

export function extensionFiles(name: string): Record<string, string> {
  const manifest = template.replaceAll('__ORIGIN__', sitePattern()).replaceAll('__NAME__', name.replace(/["\\]/g, ''));
  return { 'manifest.json': manifest, 'background.js': background, 'content.js': content, 'README.md': readme };
}

// ---- a minimal .zip writer (stored, no compression; the files are a few KB) ----
const CRC = (() => {
  const t = new Uint32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    t[n] = c >>> 0;
  }
  return t;
})();
const crc32 = (b: Uint8Array) => {
  let c = 0xffffffff;
  for (const x of b) c = CRC[(c ^ x) & 0xff]! ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
};

/** A .zip of `files` inside one folder, `dir`. */
export function zip(dir: string, files: Record<string, string>): Blob {
  const enc = new TextEncoder();
  const parts: Uint8Array[] = [];
  const central: Uint8Array[] = [];
  let offset = 0;
  for (const [file, text] of Object.entries(files)) {
    const name = enc.encode(`${dir}/${file}`);
    const data = enc.encode(text);
    const crc = crc32(data);
    const local = new DataView(new ArrayBuffer(30));
    local.setUint32(0, 0x04034b50, true); // local file header
    local.setUint16(4, 20, true); // version needed
    local.setUint16(6, 0x0800, true); // UTF-8 names
    local.setUint32(14, crc, true);
    local.setUint32(18, data.length, true);
    local.setUint32(22, data.length, true);
    local.setUint16(26, name.length, true);
    parts.push(new Uint8Array(local.buffer), name, data);
    const entry = new DataView(new ArrayBuffer(46));
    entry.setUint32(0, 0x02014b50, true); // central directory header
    entry.setUint16(4, 20, true);
    entry.setUint16(6, 20, true);
    entry.setUint16(8, 0x0800, true);
    entry.setUint32(16, crc, true);
    entry.setUint32(20, data.length, true);
    entry.setUint32(24, data.length, true);
    entry.setUint16(28, name.length, true);
    entry.setUint32(42, offset, true);
    central.push(new Uint8Array(entry.buffer), name);
    offset += 30 + name.length + data.length;
  }
  const size = central.reduce((n, p) => n + p.length, 0);
  const end = new DataView(new ArrayBuffer(22));
  end.setUint32(0, 0x06054b50, true); // end of central directory
  end.setUint16(8, Object.keys(files).length, true);
  end.setUint16(10, Object.keys(files).length, true);
  end.setUint32(12, size, true);
  end.setUint32(16, offset, true);
  return new Blob([...parts, ...central, new Uint8Array(end.buffer)] as BlobPart[], { type: 'application/zip' });
}
